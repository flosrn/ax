/**
 * THE REPORT A COMPLETION CARRIES, and the four dispositions it is named under.
 *
 * The first test is the one that keeps this runtime honest: the rule that turns
 * a dispatch record into a path exists twice — once for the brief
 * (`src/worker/report.mjs`), once here for the receiver (`docs/adr/0002`) — and
 * two rules that must agree are two rules that will drift unless a test reads
 * one record on both sides and demands one path. The record is the fixture #135
 * committed, and the expected path is the file it committed beside it.
 *
 * Everything below uses real files in a real temp tree. The containment proof
 * this module makes is `realpath`, and on macOS `/var` IS a symlink — a mocked
 * filesystem would pass a proof the real one fails.
 */

import { expect, test } from 'bun:test';
import { mkdirSync, mkdtempSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

import { reportPath as workerReportPath } from '../../src/worker/report.mjs';
import { resetDispatchNames } from './attribution.ts';
import { REPORT_CAP_BYTES, completionReport, reportPath } from './completion.ts';

const FIXTURE = join(import.meta.dir, '..', '..', 'tests', 'fixtures', 'report-record.json');
const EXPECTED = join(import.meta.dir, '..', '..', 'tests', 'fixtures', 'report-path.txt');

const DISPATCH = 'ctx_69710a418c47';

/** A record shaped like the one `ax worker start` writes, with the effects a caller chooses. */
function record(effects: unknown[], request = '137-work') {
  return {
    request,
    host: 'test.example',
    orca: 'orca',
    attempts: [
      {
        n: 1,
        settled: false,
        phases: [
          {
            name: 'worker-start',
            argv: ['orca', 'orchestration', 'worker-start'],
            receipt: { ok: true, result: { dispatchId: DISPATCH, state: 'ready', effects } },
            exit: 0,
          },
        ],
      },
    ],
  };
}

/** A worktree in a fresh temp tree, plus the Report path derived under it. */
function worktree(request = '137-work') {
  const path = mkdtempSync(join(tmpdir(), 'ax-report-'));
  const derived = join(path, '.scratch', 'report', `${request}.md`);
  return { path, derived, rec: record([{ kind: 'worktree', id: `repo::${path}` }], request) };
}

function withReport(body: string, request = '137-work') {
  const wt = worktree(request);
  mkdirSync(dirname(wt.derived), { recursive: true });
  writeFileSync(wt.derived, body);
  return wt;
}

/** A completion exactly as Orca delivers one: `dispatch:<id>` handle, payload as a string. */
function completion(payload: Record<string, unknown> | null = null) {
  return {
    id: 'm1',
    type: 'worker_done',
    body: 'Opened PR #99. Both suites green. Nothing left.',
    from_handle: `dispatch:${DISPATCH}`,
    ...(payload === null ? {} : { payload: JSON.stringify(payload) }),
  };
}

/** The receiver's own wiring, with the record lookup and the host answer injected. */
function deps(rec: unknown, environment = '') {
  return {
    record: (id: string) => (id === DISPATCH ? { request: '137-work', json: rec } : null),
    environmentOf: () => environment,
  };
}

