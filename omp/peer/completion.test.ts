test('the fixture #135 committed yields the same path here as in the worker module', () => {
  const rec = JSON.parse(readFileSync(FIXTURE, 'utf8'));
  const expected = readFileSync(EXPECTED, 'utf8').trim();

  expect(reportPath(rec).path).toBe(expected);
  // And against the other implementation directly, not only its committed
  // answer: the fixture file could be regenerated by one side alone.
  expect(reportPath(rec).path).toBe(workerReportPath(rec).path);
});

// The case list below is the twin's maintenance contract, and it is kept by
// hand: a new refusal branch on EITHER side of the Report-path rule joins this
// list in the same commit that adds it — never a follow-up. Measured within
// hours of the rule's birth (#143): #136 split the src side into
// `reportPathFor({ worktree, request })` + `reportPath(rec)` and re-worded one
// refusal, and #137's twin drifted the same day; this test caught it on the
// merged tree. So the src side is now TWO functions, and a split or a rewording
// over there moves two wordings here, not one. The twin exists at all because
// importing `reportPath` into the receiver would evaluate the CLI emitter chain
// at every session's startup; this list is the price of that ruling.
test('both rules refuse the same records, and neither invents a path key', () => {
  const cases: Array<[string, unknown]> = [
    ['no worktree', record([])],
    ['two worktrees', record([{ kind: 'worktree', id: 'repo::/wt-a' }, { kind: 'worktree', id: 'repo::/wt-b' }])],
    ['a traversal request', record([{ kind: 'worktree', id: 'repo::/wt' }], '../../outside')],
    // Reachable, and newly worded by #136's `reportPathFor`: an effect naming a
    // relative directory. Both rules must refuse it the same way, in the same
    // order relative to the request check.
    ['a relative worktree', record([{ kind: 'worktree', id: 'repo::wt/relative' }])],
    ['a relative worktree and a bad request', record([{ kind: 'worktree', id: 'repo::wt/relative' }], '..')],
  ];

  for (const [why, rec] of cases) {
    const mine = reportPath(rec);
    const theirs = workerReportPath(rec);
    expect(`${why}: ${'path' in mine}`).toBe(`${why}: false`);
    expect(`${why}: ${'path' in theirs}`).toBe(`${why}: false`);
    expect(mine.reason).toBe(theirs.reason);
  }
});

