// `ax triage publish` — the one place a triage verdict reaches the tracker.
//
// A triage child writes a draft and mutates nothing, so the mutation has to
// happen somewhere. Leaving it to the operator's own `gh` calls is not a smaller
// surface, it is an untested one — and it is precisely the failure this whole
// noun is paid for: on 2026-08-10 four issues landed with three empty label
// groups each, because applying five groups by hand is data entry and data entry
// gets skipped.
//
// So this verb is narrow and unfriendly on purpose:
//
//   * it applies EXACTLY what the draft names, and refuses a draft that names
//     nothing — it never composes, never guesses a missing group
//   * it reads every draft before the first `gh` call, so a batch cannot land
//     half applied
//   * it grades each directive against what the issue ALREADY CARRIES, read on
//     that same tracker read: a `Labels:` name in the PROVENANCE group the
//     issue already wears, or a `Remove labels:` name it does not wear, is a
//     directive that changes nothing and it refuses the batch rather than
//     dropping the name — dropping would be composing (#101)
//   * it asks the TRACKER whether this publication already landed there, and
//     refuses a second one unless `--republish` says so out loud (ofmchat #98)
//   * it NEVER closes an issue. A child may recommend wontfix; closing is the
//     one gesture the reporter is owed by a human
//   * a `custom` job is not publishable at all, by name: its draft is a report
//     to you, not a tracker mutation

